// Turns docs/chatbot-questions-and-answers.md into lib/chatbot/knowledge.ts (the knowledge the chatbot answers from).
// Run after you edit the Q&A file:   npm run chatbot:kb
import fs from "node:fs";

const SRC = new URL("../docs/chatbot-questions-and-answers.md", import.meta.url);
const OUT = new URL("../lib/chatbot/knowledge.ts", import.meta.url);

let md = fs.readFileSync(SRC, "utf8").replace(/\r\n/g, "\n");

// Keep only the numbered question sections: drop the intro/rules (they live in the system prompt) and the owner's checklist.
const start = md.indexOf("## 1. ");
const end = md.indexOf("## Checklist");
if (start < 0 || end < 0) throw new Error("The Q&A file layout changed: could not find the section markers.");
md = md.slice(start, end).trim();

// Light tidy so the model reads it cleanly.
md = md
  .replace(/^---$/gm, "")                                  // horizontal rules
  .replace(/\*\*/g, "")                                    // bold markers
  .replace(/^Buttons: .*$/gm, "")                          // UI button hints are for the widget, not the answer
  .replace(/⚠️ Your answer: _+/g, "[NOT PROVIDED YET: do not guess. Say the team will confirm on WhatsApp.]")
  .replace(/⚠️ Your hours: _+/g, "[NOT PROVIDED YET: do not guess. Say the team will confirm on WhatsApp.]")
  .replace(/⚠️ Your list: _+/g, "[NOT PROVIDED YET: do not guess. Say the team will confirm on WhatsApp.]")
  .replace(/\n{3,}/g, "\n\n")
  .trim();

const questions = (md.match(/^Q\d+\./gm) || []).length;
const out = `// GENERATED by scripts/build-chatbot-kb.mjs from docs/chatbot-questions-and-answers.md. Do not edit by hand:
// edit the .md file and run "npm run chatbot:kb".
export const KNOWLEDGE_BASE = ${JSON.stringify(md)};
export const KNOWLEDGE_QUESTIONS = ${questions};
`;
fs.mkdirSync(new URL("../lib/chatbot/", import.meta.url), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`knowledge.ts written: ${questions} questions, ${md.length} characters (about ${Math.round(md.length / 4)} tokens)`);
